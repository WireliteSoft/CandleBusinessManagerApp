import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const masterPath = join(root, 'storage', 'master', 'candles-business.db');
const accountsPath = join(root, 'storage', 'accounts');
const migrationsPath = join(root, 'migrations');
const outputPath = join(root, 'exports', 'd1-import.sql');
const chunksPath = join(root, 'exports', 'd1-import-chunks');
const maxChunkBytes = 80_000;
const maxInlineValueBytes = 500;

function quoteIdentifier(value) {
  return `"${value.replaceAll('"', '""')}"`;
}

function sqlValue(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL';
  if (typeof value === 'bigint') return value.toString();
  if (value instanceof Uint8Array) return value.byteLength <= maxInlineValueBytes ? `X'${Buffer.from(value).toString('hex')}'` : "X''";
  const text = String(value);
  return Buffer.byteLength(text, 'utf8') <= maxInlineValueBytes ? `'${text.replaceAll("'", "''")}'` : "''";
}

function tableNames(db) {
  return db.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all()
    .map((row) => row.name);
}

function columns(db, table) {
  return db.prepare(`PRAGMA table_info(${quoteIdentifier(table)})`).all().map((row) => row.name);
}

function dependencyOrderedTables(db) {
  const pending = new Set(tableNames(db));
  const ordered = [];
  while (pending.size) {
    const ready = [...pending].filter((table) => db.prepare(`PRAGMA foreign_key_list(${quoteIdentifier(table)})`).all()
      .every((foreignKey) => foreignKey.table === table || !pending.has(foreignKey.table)));
    const next = ready.length ? ready.sort() : [...pending].sort();
    for (const table of next) { pending.delete(table); ordered.push(table); }
  }
  return ordered;
}

function createTargetSchema() {
  const target = new DatabaseSync(':memory:');
  for (const filename of readdirSync(migrationsPath).filter((name) => name.endsWith('.sql')).sort()) {
    target.exec(readFileSync(join(migrationsPath, filename), 'utf8'));
  }
  return target;
}

function appendRows(lines, source, targetColumns, table, accountId) {
  const sourceColumns = columns(source, table);
  const needsAccountId = targetColumns.includes('account_id');
  const canSupplyAccountId = sourceColumns.includes('account_id') || Boolean(accountId);
  if (needsAccountId && !canSupplyAccountId) return 0;
  const selectedColumns = targetColumns.filter((column) => sourceColumns.includes(column) || (column === 'account_id' && Boolean(accountId)));
  if (!selectedColumns.length || (accountId && !selectedColumns.includes('account_id'))) return 0;

  const rows = source.prepare(`SELECT * FROM ${quoteIdentifier(table)}`).all();
  let inserted = 0;
  for (const row of rows) {
    if (needsAccountId && !accountId && !row.account_id) continue;
    const values = selectedColumns.map((column) => column === 'account_id' && accountId ? accountId : row[column]);
    lines.push(`INSERT OR IGNORE INTO ${quoteIdentifier(table)} (${selectedColumns.map(quoteIdentifier).join(', ')}) VALUES (${values.map(sqlValue).join(', ')});`);
    inserted += 1;
  }
  return inserted;
}

const target = createTargetSchema();
const targetTables = new Map(tableNames(target).map((table) => [table, columns(target, table)]));
const lines = [
  '-- Generated by scripts/export-sqlite-to-d1.mjs. Do not edit manually.',
  '-- Apply all migrations to an empty D1 database before importing this file.',
  'PRAGMA defer_foreign_keys = ON;',
  'BEGIN TRANSACTION;',
];
const counts = new Map();
const skippedAccounts = [];
const master = new DatabaseSync(masterPath, { readOnly: true });
const accountIds = new Set(master.prepare('SELECT id FROM Account').all().map((row) => String(row.id)));

for (const table of tableNames(master)) {
  const targetColumns = targetTables.get(table);
  if (!targetColumns) continue;
  counts.set(table, (counts.get(table) || 0) + appendRows(lines, master, targetColumns, table, null));
}
master.close();

for (const filename of readdirSync(accountsPath).filter((name) => name.endsWith('.db')).sort()) {
  const accountId = basename(filename, '.db');
  if (!accountIds.has(accountId)) {
    skippedAccounts.push(accountId);
    continue;
  }
  const account = new DatabaseSync(join(accountsPath, filename), { readOnly: true });
  for (const table of tableNames(account)) {
    const targetColumns = targetTables.get(table);
    if (!targetColumns || !targetColumns.includes('account_id')) continue;
    counts.set(table, (counts.get(table) || 0) + appendRows(lines, account, targetColumns, table, accountId));
  }
  account.close();
}

lines.push('COMMIT;');
lines.push('PRAGMA defer_foreign_keys = OFF;');
const sql = `${lines.join('\n')}\n`;

// Validate syntax and foreign keys with the exact target schema before creating an import file.
// Foreign keys are disabled only for this diagnostic pass so legacy dangling rows can be removed.
target.exec('PRAGMA foreign_keys = OFF;');
target.exec(sql);
target.exec('PRAGMA foreign_keys = ON;');
const discardedRows = [];
for (;;) {
  const integrityErrors = target.prepare('PRAGMA foreign_key_check').all();
  if (!integrityErrors.length) break;
  for (const error of integrityErrors) {
    target.prepare(`DELETE FROM ${quoteIdentifier(error.table)} WHERE rowid = ?`).run(error.rowid);
    discardedRows.push(`${error.table}:${error.rowid}`);
  }
}

const exportLines = [
  '-- Generated by scripts/export-sqlite-to-d1.mjs. Do not edit manually.',
  '-- Apply all migrations to an empty D1 database before importing this file.',
  'PRAGMA defer_foreign_keys = ON;',
  'BEGIN TRANSACTION;',
];
for (const table of dependencyOrderedTables(target)) {
  const tableColumns = columns(target, table);
  const rows = target.prepare(`SELECT * FROM ${quoteIdentifier(table)}`).all();
  for (const row of rows) {
    exportLines.push(`INSERT OR IGNORE INTO ${quoteIdentifier(table)} (${tableColumns.map(quoteIdentifier).join(', ')}) VALUES (${tableColumns.map((column) => sqlValue(row[column])).join(', ')});`);
  }
}
exportLines.push('COMMIT;');
exportLines.push('PRAGMA defer_foreign_keys = OFF;');
const cleanSql = `${exportLines.join('\n')}\n`;
target.close();

const strictTarget = createTargetSchema();
for (const statement of exportLines.slice(4, -2)) {
  try {
    strictTarget.exec(statement);
  } catch (error) {
    strictTarget.close();
    throw new Error(`D1 import dependency failure: ${statement.slice(0, 300)}\n${error.message}`);
  }
}
strictTarget.close();

mkdirSync(join(root, 'exports'), { recursive: true });
rmSync(outputPath, { force: true });
writeFileSync(outputPath, cleanSql, 'utf8');
rmSync(chunksPath, { force: true, recursive: true });
mkdirSync(chunksPath, { recursive: true });

const insertStatements = exportLines.slice(4, -2);
const chunks = [];
let statements = [];
let bytes = 0;
for (const statement of insertStatements) {
  const statementBytes = Buffer.byteLength(statement, 'utf8') + 1;
  if (statements.length && bytes + statementBytes > maxChunkBytes) {
    chunks.push(statements);
    statements = [];
    bytes = 0;
  }
  statements.push(statement);
  bytes += statementBytes;
}
if (statements.length) chunks.push(statements);
for (const [index, chunk] of chunks.entries()) {
  const filename = `${String(index + 1).padStart(4, '0')}.sql`;
  writeFileSync(join(chunksPath, filename), [
    ...chunk,
    '',
  ].join('\n'), 'utf8');
}

console.log(`Created ${outputPath}`);
console.log(`Created ${chunks.length} dashboard import chunks in ${chunksPath}`);
console.log([...counts.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([table, count]) => `${table}: ${count}`).join('\n'));
if (skippedAccounts.length) {
  console.log(`Skipped orphan account databases: ${skippedAccounts.join(', ')}`);
}
if (discardedRows.length) {
  console.log(`Discarded dangling legacy rows: ${discardedRows.join(', ')}`);
}
